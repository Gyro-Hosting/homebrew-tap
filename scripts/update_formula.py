#!/usr/bin/env python3
"""Regenerate Formula/gyro.rb from the latest (or given) Gyro-Hosting/gyro-cli release.

The release checksum file (gyro_<v>_SHA256SUMS) is verified against its detached GPG
signature with the Gyro Hosting release key before any hash is written into the formula.

usage: update_formula.py [vX.Y.Z]      (needs: gpg, network; GITHUB_TOKEN optional)
"""
import json, os, re, subprocess, sys, tempfile, urllib.request

REPO = "Gyro-Hosting/gyro-cli"
FPR = "E96BE9635E77A0D9119AC8C3A7986589A154B990"
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "Formula", "gyro.rb")
PLATFORMS = [("macos", "arm", "darwin_arm64"), ("macos", "intel", "darwin_amd64"),
             ("linux", "arm", "linux_arm64"), ("linux", "intel", "linux_amd64")]

def get(url, binary=False):
    h = {"User-Agent": "gyro-homebrew-tap"}
    if "api.github.com" in url and os.environ.get("GITHUB_TOKEN"):
        h["Authorization"] = "Bearer " + os.environ["GITHUB_TOKEN"]
    with urllib.request.urlopen(urllib.request.Request(url, headers=h), timeout=60) as r:
        d = r.read()
    return d if binary else d.decode()

def main():
    if len(sys.argv) > 1:
        tag = sys.argv[1]
    else:
        tag = json.loads(get(f"https://api.github.com/repos/{REPO}/releases/latest"))["tag_name"]
    if not re.fullmatch(r"v\d+\.\d+\.\d+", tag):
        sys.exit(f"unexpected tag: {tag}")
    ver = tag[1:]
    base = f"https://github.com/{REPO}/releases/download/{tag}"
    sums = get(f"{base}/gyro_{ver}_SHA256SUMS", True)
    sig = get(f"{base}/gyro_{ver}_SHA256SUMS.sig", True)
    with tempfile.TemporaryDirectory() as d:
        env = dict(os.environ, GNUPGHOME=d)
        subprocess.run(["gpg", "--batch", "--quiet", "--import", os.path.join(HERE, "gyro-release-signing-public.asc")],
                       env=env, check=True, capture_output=True)
        open(os.path.join(d, "s"), "wb").write(sums); open(os.path.join(d, "s.sig"), "wb").write(sig)
        r = subprocess.run(["gpg", "--batch", "--status-fd", "1", "--verify", os.path.join(d, "s.sig"), os.path.join(d, "s")],
                           env=env, capture_output=True, text=True)
        if r.returncode != 0 or f"VALIDSIG {FPR}" not in r.stdout:
            sys.exit("SHA256SUMS signature verification FAILED")
    hashes = {}
    for line in sums.decode().splitlines():
        p = line.split()
        if len(p) == 2: hashes[p[1]] = p[0]
    blocks = {}
    for os_, cpu, suf in PLATFORMS:
        fn = f"gyro_{ver}_{suf}.tar.gz"
        if not re.fullmatch(r"[0-9a-f]{64}", hashes.get(fn, "")):
            sys.exit(f"missing checksum for {fn}")
        blocks.setdefault(os_, []).append(
            f"    on_{cpu} do\n"
            f"      url \"https://github.com/{REPO}/releases/download/{tag}/gyro_{ver}_{suf}.tar.gz\"\n"
            f"      sha256 \"{hashes[fn]}\"\n"
            f"    end\n")
    body = f'''# typed: false
# frozen_string_literal: true

# Generated by scripts/update_formula.py from the signed release checksums. Do not edit by hand.
class Gyro < Formula
  desc "Official command-line interface for Gyro Hosting"
  homepage "https://www.gyrohosting.com/developers/"
  license "MPL-2.0"

  on_macos do
{"".join(blocks["macos"])}  end

  on_linux do
{"".join(blocks["linux"])}  end

  def install
    bin.install "gyro"
    man1.install Dir["man/*.1"]
    bash_completion.install "completions/gyro.bash" => "gyro"
    zsh_completion.install "completions/_gyro"
    fish_completion.install "completions/gyro.fish"
  end

  test do
    assert_match version.to_s, shell_output("#{{bin}}/gyro --version")
  end
end
'''
    old = open(OUT).read() if os.path.exists(OUT) else ""
    if old == body:
        print(f"Formula already at {ver}"); return
    open(OUT, "w").write(body)
    print(f"Formula updated to {ver}")

if __name__ == "__main__":
    main()
